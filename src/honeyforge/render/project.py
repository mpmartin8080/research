"""Render a spec into a self-contained Docker build context + compose project."""

from __future__ import annotations

import html
import json
import shlex
import shutil
from importlib import resources
from pathlib import Path
from string import Template
from typing import Any

import yaml

from honeyforge.canary import OPENCANARY_VERSION
from honeyforge.canary.config import EVENT_LOG, SSH_KEY_DIR, TLS_CERT, TLS_KEY, build_config, skin_name, tls_hostname
from honeyforge.canary.modules import MODULES
from honeyforge.spec.loader import dump_spec
from honeyforge.spec.models import HoneypotSpec, NetworkMode
from honeyforge.spec.policy import check_policy, has_errors

DEFAULT_BASE_IMAGE = "python:3.12-slim-bookworm"
DEFAULT_NETGUARD_IMAGE = "alpine:3.20"
CANARY_UID = 10001

# Container resource ceilings. OpenCanary is a single Twisted process.
LIMITS = {"pids_limit": 128, "mem_limit": "256m", "cpus": 0.5}

DOCKERFILE = Template("""\
# Generated by HoneyForge. Do not edit; re-render from the spec.
FROM $base AS build
ENV PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1
COPY requirements.txt /tmp/requirements.txt
RUN python -m venv /opt/venv && /opt/venv/bin/pip install -r /tmp/requirements.txt

FROM $base
ENV PATH=/opt/venv/bin:$$PATH PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1
COPY --from=build /opt/venv /opt/venv
COPY keygen.py /tmp/keygen.py
COPY skins/ /tmp/skins/
RUN groupadd -r -g $uid canary \\
 && useradd -r -u $uid -g canary -d /nonexistent -s /usr/sbin/nologin canary \\
 && python /tmp/keygen.py $ssh_dir $tls_cert $tls_key $keygen_args \\
 && chown -R root:canary /etc/honeyforge && chmod 750 $ssh_dir $tls_dir \\
 && skindir="$$(python -c 'import importlib.util,os; print(os.path.join(importlib.util.find_spec("opencanary").submodule_search_locations[0], "modules", "data", "http", "skin"))')" \\
 && cp -r /tmp/skins/. "$$skindir/" \\
 && rm -rf /tmp/keygen.py /tmp/skins \\
 && mkdir -p $log_dir && chown canary:canary $log_dir
COPY opencanary.conf /etc/opencanaryd/opencanary.conf
USER $uid:$uid
WORKDIR /tmp
ENTRYPOINT ["/opt/venv/bin/twistd", "--nodaemon", "--logfile=-", "--pidfile=/tmp/twistd.pid", "--python=/opt/venv/bin/opencanary.tac"]
""")


ERROR_PAGES = {
    "redirect.html": '<html><head><title>Moved</title></head><body>Redirecting to <a href="/index.html">'
                     "/index.html</a></body></html>\n",
    "400.html": "<html><head><title>400 Bad Request</title></head><body><h1>Bad Request</h1></body></html>\n",
    "403.html": "<html><head><title>403 Forbidden</title></head><body><h1>Forbidden</h1></body></html>\n",
    "404.html": "<html><head><title>404 Not Found</title></head><body><h1>Not Found</h1></body></html>\n",
}

NETGUARD_DOCKERFILE = Template("""\
# Generated by HoneyForge. Network-namespace owner enforcing default-deny egress.
FROM $base
RUN apk add --no-cache iptables ip6tables setpriv
COPY netguard.sh /usr/local/bin/netguard.sh
RUN chmod 0555 /usr/local/bin/netguard.sh
ENTRYPOINT ["/usr/local/bin/netguard.sh"]
""")


def render_project(spec: HoneypotSpec, outdir: str | Path, base_image: str = DEFAULT_BASE_IMAGE,
                   netguard_base: str = DEFAULT_NETGUARD_IMAGE) -> Path:
    """Write the build context for `spec` into `outdir` and return the compose file path.
    Refuses specs that fail policy."""
    findings = check_policy(spec)
    if has_errors(findings):
        raise ValueError("spec fails policy:\n" + "\n".join(str(f) for f in findings))
    if spec.network.mode != NetworkMode.BRIDGE:
        raise NotImplementedError("macvlan/ipvlan rendering lands with the L2 signal engine (phase 8)")

    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    files = resources.files("honeyforge") / "render" / "files"

    (out / "opencanary.conf").write_text(json.dumps(build_config(spec), indent=2) + "\n", encoding="utf-8")
    (out / "requirements.txt").write_text(f"opencanary=={OPENCANARY_VERSION}\n", encoding="utf-8")
    (out / "keygen.py").write_text((files / "keygen.py").read_text(encoding="utf-8"), encoding="utf-8")
    _render_skins(spec, out / "skins", (files / "login.html").read_text(encoding="utf-8"))
    (out / "Dockerfile").write_text(_dockerfile(spec, base_image), encoding="utf-8")
    netguard = out / "netguard"
    netguard.mkdir(exist_ok=True)
    (netguard / "Dockerfile").write_text(NETGUARD_DOCKERFILE.substitute(base=netguard_base), encoding="utf-8")
    # LF endings regardless of host OS: this runs under /bin/sh in the container.
    (netguard / "netguard.sh").write_bytes((files / "netguard.sh").read_text(encoding="utf-8")
                                           .replace("\r\n", "\n").encode())
    compose = out / "compose.yaml"
    compose.write_text(yaml.safe_dump(compose_dict(spec), sort_keys=False), encoding="utf-8")
    (out / ".dockerignore").write_text("compose.yaml\nspec.lock.yaml\nnetguard/\n", encoding="utf-8")
    dump_spec(spec, out / "spec.lock.yaml")
    return compose


def _render_skins(spec: HoneypotSpec, skins_dir: Path, template: str) -> None:
    if skins_dir.exists():
        shutil.rmtree(skins_dir)
    for svc in spec.services:
        if svc.emulator not in ("http", "https") or "skin" in svc.options:
            continue
        d = skins_dir / skin_name(svc)
        (d / "static").mkdir(parents=True)
        values = {k: html.escape(v) for k, v in {
            "title": svc.display_name or spec.persona.role,
            "org": spec.persona.org_name,
            "hostname": spec.persona.hostname,
        }.items()}
        (d / "index.html").write_text(Template(template).substitute(values), encoding="utf-8")
        # Every page OpenCanary's http/https modules may serve from a skin directory.
        for page, body in ERROR_PAGES.items():
            (d / page).write_text(body, encoding="utf-8")
    skins_dir.mkdir(exist_ok=True)  # COPY needs the dir even when empty
    (skins_dir / ".keep").touch()


def _dockerfile(spec: HoneypotSpec, base_image: str) -> str:
    sans = [h for h in spec.persona.public_hostnames if h != tls_hostname(spec)]
    keygen_args = " ".join(shlex.quote(a) for a in [spec.persona.org_name, tls_hostname(spec), *sans])
    return DOCKERFILE.substitute(
        base=base_image, uid=CANARY_UID, ssh_dir=SSH_KEY_DIR, tls_cert=TLS_CERT, tls_key=TLS_KEY,
        tls_dir=str(Path(TLS_CERT).parent.as_posix()), keygen_args=keygen_args,
        log_dir=str(Path(EVENT_LOG).parent.as_posix()),
    )


def _ports(spec: HoneypotSpec) -> list[str]:
    return [f"{svc.publish_port}:{svc.listen_port}/{MODULES[svc.emulator].transport}"
            for svc in spec.services if svc.publish_port]


def _healthcheck(spec: HoneypotSpec) -> dict[str, Any] | None:
    tcp = next((s for s in spec.services if MODULES[s.emulator].transport == "tcp"), None)
    if tcp is None:
        return None
    probe = f"import socket; socket.create_connection(('127.0.0.1', {tcp.listen_port}), 3).close()"
    return {"test": ["CMD", "/opt/venv/bin/python", "-c", probe],
            "interval": "30s", "timeout": "5s", "retries": 3, "start_period": "20s"}


def compose_dict(spec: HoneypotSpec) -> dict[str, Any]:
    labels = {"io.honeyforge.honeypot": spec.name, "io.honeyforge.arm": spec.experiment_arm,
              "io.honeyforge.archetype": spec.archetype}
    # netguard owns the network namespace (ports, hostname, egress rules); the decoy
    # joins it. Its capabilities are held only until the rules are applied; netguard.sh
    # then clears them from the bounding set and idles as nobody.
    netguard: dict[str, Any] = {
        "build": {"context": "./netguard"},
        "image": f"honeyforge/{spec.name}-netguard:latest",
        "hostname": spec.persona.hostname,
        "read_only": True,
        "cap_drop": ["ALL"],
        "cap_add": ["NET_ADMIN", "SETUID", "SETGID", "SETPCAP"],
        "security_opt": ["no-new-privileges:true"],
        "tmpfs": ["/run:size=1m"],
        "ports": _ports(spec),
        "pids_limit": 16, "mem_limit": "32m", "cpus": 0.1,
        "restart": "unless-stopped",
        "networks": ["exposed"],
        "labels": labels,
    }
    decoy: dict[str, Any] = {
        "build": {"context": "."},
        "image": f"honeyforge/{spec.name}:latest",
        "network_mode": "service:netguard",
        "depends_on": {"netguard": {"condition": "service_started", "restart": True}},
        "read_only": True,
        "cap_drop": ["ALL"],
        "security_opt": ["no-new-privileges:true"],
        "tmpfs": ["/tmp:size=16m,mode=1777", "/var/tmp:size=8m,mode=1777"],
        "volumes": [f"events:{Path(EVENT_LOG).parent.as_posix()}"],
        **LIMITS,
        "restart": "unless-stopped",
        "labels": labels,
    }
    if hc := _healthcheck(spec):
        decoy["healthcheck"] = hc
    return {
        "name": f"hf-{spec.name}",
        "services": {"netguard": netguard, "decoy": decoy},
        "networks": {"exposed": {"driver": "bridge"}},
        "volumes": {"events": {}},
    }
